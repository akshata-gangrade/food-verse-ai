import React, { useState, useEffect } from 'react';
import { recipeService } from '../api/services';
import { GuidedCookingModal } from '../components/GuidedCookingModal';
import {
  BookMarked,
  Clock,
  Flame,
  Play,
  Trash2,
  ChefHat,
  Eye,
  X
} from 'lucide-react';
import toast from 'react-hot-toast';

export const SavedRecipes = () => {
  const [recipes, setRecipes] = useState([]);
  const [loading, setLoading] = useState(true);
  const [activeRecipeForCooking, setActiveRecipeForCooking] = useState(null);
  const [viewRecipeModal, setViewRecipeModal] = useState(null);

  useEffect(() => {
    loadRecipes();
  }, []);

  const loadRecipes = async () => {
    try {
      const res = await recipeService.listRecipes();
      setRecipes(res.data);
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  const handleDelete = async (id, title) => {
    if (!confirm(`Are you sure you want to delete "${title}"?`)) return;
    try {
      await recipeService.deleteRecipe(id);
      setRecipes((prev) => prev.filter((r) => r.id !== id));
      toast.success('Recipe removed.');
    } catch (err) {
      console.error(err);
      toast.error('Failed to delete recipe.');
    }
  };

  if (loading) {
    return (
      <div className="flex items-center justify-center min-h-[300px]">
        <div className="w-8 h-8 border-4 border-forest border-t-transparent rounded-full animate-spin"></div>
      </div>
    );
  }

  return (
    <div className="space-y-6 animate-fadeIn pb-12">
      <div>
        <h2 className="font-serif text-2xl md:text-3xl font-bold text-forest">
          Saved Recipes Collection
        </h2>
        <p className="text-sm text-charcoal-muted mt-1">
          Explore recipes generated by your Cooking Assistant with integrated step-by-step guided timers.
        </p>
      </div>

      {recipes.length === 0 ? (
        <div className="bg-white rounded-card p-12 text-center border border-mint-light shadow-soft max-w-lg mx-auto space-y-4">
          <div className="w-16 h-16 rounded-2xl bg-mint-light text-forest flex items-center justify-center mx-auto">
            <BookMarked className="w-8 h-8" />
          </div>
          <h3 className="font-serif font-bold text-xl text-forest">No saved recipes yet</h3>
          <p className="text-xs text-charcoal-muted leading-relaxed">
            Ask the Smart Cooking Assistant for recipe ideas and click "Save Recipe" to build your custom cookbook!
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">
          {recipes.map((recipe) => (
            <div
              key={recipe.id}
              className="bg-white rounded-card border border-mint-light p-6 shadow-soft hover:shadow-elevated transition flex flex-col justify-between space-y-4"
            >
              <div className="space-y-2">
                <div className="flex items-center justify-between">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-forest bg-mint-light px-2.5 py-0.5 rounded-full">
                    {recipe.cuisine || 'Gourmet'}
                  </span>
                  <div className="flex items-center gap-1">
                    <button
                      onClick={() => setViewRecipeModal(recipe)}
                      className="p-1.5 text-charcoal-muted hover:text-forest transition"
                      title="View Details"
                    >
                      <Eye className="w-4 h-4" />
                    </button>
                    <button
                      onClick={() => handleDelete(recipe.id, recipe.title)}
                      className="p-1.5 text-charcoal-muted hover:text-terracotta transition"
                      title="Delete Recipe"
                    >
                      <Trash2 className="w-4 h-4" />
                    </button>
                  </div>
                </div>

                <h3 className="font-serif font-bold text-lg text-charcoal line-clamp-1">
                  {recipe.title}
                </h3>

                <div className="flex items-center gap-4 text-xs text-charcoal-muted pt-1">
                  <span className="flex items-center gap-1 font-semibold text-forest">
                    <Clock className="w-3.5 h-3.5" />
                    {recipe.cook_time_minutes || 20}m cook
                  </span>
                  <span className="flex items-center gap-1 font-semibold text-amber-700">
                    <Flame className="w-3.5 h-3.5" />
                    ~{recipe.calories_per_serving || 400} kcal
                  </span>
                  <span>{recipe.servings || 2} servings</span>
                </div>

                {/* Ingredients snippet */}
                <div className="pt-2">
                  <span className="text-[10px] font-bold text-charcoal-muted uppercase tracking-wider block mb-1">
                    Ingredients ({recipe.ingredients?.length}):
                  </span>
                  <p className="text-xs text-charcoal-muted line-clamp-2">
                    {recipe.ingredients?.join(', ')}
                  </p>
                </div>
              </div>

              {/* Action: Start guided cooking */}
              <div className="pt-3 border-t border-mint-light flex items-center justify-between">
                <button
                  onClick={() => setActiveRecipeForCooking(recipe)}
                  className="w-full py-2.5 px-4 rounded-xl bg-forest hover:bg-forest-light text-white text-xs font-semibold flex items-center justify-center gap-2 shadow-sm transition"
                >
                  <Play className="w-3.5 h-3.5 fill-white" />
                  Start Guided Cooking
                </button>
              </div>
            </div>
          ))}
        </div>
      )}

      {/* View Recipe Modal */}
      {viewRecipeModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-charcoal/60 backdrop-blur-sm">
          <div className="bg-white rounded-card shadow-elevated max-w-2xl w-full max-h-[85vh] overflow-y-auto p-6 md:p-8 border border-mint-light">
            <div className="flex items-center justify-between pb-4 border-b border-mint-light mb-4">
              <div>
                <span className="text-xs font-bold uppercase tracking-wider text-forest block">
                  {viewRecipeModal.cuisine}
                </span>
                <h3 className="font-serif text-2xl font-bold text-charcoal">
                  {viewRecipeModal.title}
                </h3>
              </div>
              <button
                onClick={() => setViewRecipeModal(null)}
                className="p-1 rounded-lg text-charcoal-muted hover:text-charcoal"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            <div className="space-y-4 text-xs text-charcoal">
              <div>
                <h4 className="font-bold uppercase tracking-wider text-charcoal-muted mb-2">Ingredients:</h4>
                <ul className="grid grid-cols-1 sm:grid-cols-2 gap-1.5 list-disc list-inside">
                  {viewRecipeModal.ingredients?.map((ing, i) => (
                    <li key={i}>{ing}</li>
                  ))}
                </ul>
              </div>

              <div className="pt-3 border-t border-mint-light">
                <h4 className="font-bold uppercase tracking-wider text-charcoal-muted mb-2">Instructions:</h4>
                <ol className="space-y-2 list-decimal list-inside">
                  {viewRecipeModal.instructions?.map((step, idx) => (
                    <li key={idx} className="leading-relaxed">
                      <span className="font-medium">{step.text}</span>
                      {step.timer_seconds > 0 && (
                        <span className="text-forest font-semibold ml-2">
                          ({Math.round(step.timer_seconds / 60)} min timer)
                        </span>
                      )}
                    </li>
                  ))}
                </ol>
              </div>

              <div className="pt-4 border-t border-mint-light flex justify-end gap-2">
                <button
                  onClick={() => {
                    const r = viewRecipeModal;
                    setViewRecipeModal(null);
                    setActiveRecipeForCooking(r);
                  }}
                  className="px-4 py-2 rounded-xl bg-forest text-white font-semibold flex items-center gap-2 hover:bg-forest-light"
                >
                  <Play className="w-3.5 h-3.5 fill-white" />
                  Cook Now
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Guided Cooking Modal */}
      {activeRecipeForCooking && (
        <GuidedCookingModal
          recipe={activeRecipeForCooking}
          onClose={() => setActiveRecipeForCooking(null)}
        />
      )}
    </div>
  );
};
